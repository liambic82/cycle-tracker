import { readFile, writeFile } from 'node:fs/promises';
import policy from '../src/content/privacy.json' with { type: 'json' };

const escape = (value) =>
  value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
const shell = (title, body) => `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="referrer" content="no-referrer"><meta name="color-scheme" content="light"><title>${title} · Trifelle</title><link rel="icon" href="icon.svg" type="image/svg+xml"><link rel="stylesheet" href="privacy.css"></head>
<body><a class="skip" href="#main">Skip to content</a><header><a class="brand" href="support.html"><img src="icon.svg" width="42" height="42" alt="">Trifelle</a><nav aria-label="Support navigation"><a href="support.html">Support</a><a href="privacy.html">Privacy</a></nav></header><main id="main">${body}</main><footer>Trifelle · ${escape(policy.publisher)} · <a href="mailto:${policy.email}">${policy.email}</a></footer></body></html>
`;
const privacy = shell(
  'Privacy',
  `<h1>${escape(policy.title)}</h1><p class="muted">Updated ${escape(policy.updated)} · ${escape(policy.publisher)}</p><p>${escape(policy.intro)}</p><nav aria-label="Policy sections"><ul>${policy.sections.map((section) => `<li><a href="#${section.id}">${escape(section.title)}</a></li>`).join('')}</ul></nav>${policy.sections.map((section) => `<section id="${section.id}"><h2>${escape(section.title)}</h2>${section.paragraphs.map((p) => `<p>${escape(p)}</p>`).join('')}</section>`).join('')}`,
);
const support = shell(
  'Support',
  `<h1>Trifelle support</h1><p>A private period and wellbeing journal by ${escape(policy.publisher)}.</p><p>For support or privacy requests, email <a href="mailto:${policy.email}?subject=Trifelle%20support">${policy.email}</a>. Include your app version, phone model, operating-system version and the steps that led to the problem. Use fictional records when possible.</p><p>Please do not send passphrases, backups or unredacted health records.</p><section><h2>Keep a backup</h2><p>Use Download encrypted backup in the app's data controls. Save the file somewhere you trust. To restore, lock the app, choose Restore a backup and enter the passphrase used when that backup was created. Restoring replaces the journal on that installation.</p><p>Biometric unlock is optional. It does not replace the need to keep your passphrase. There is no password-reset or journal-recovery service.</p></section><section><h2>Bring in wearable sleep</h2><p>Sync your wearable with its source app first, and allow that app to write sleep to Android Health Connect. In Trifelle's wearable sleep controls, grant sleep access, load nights, choose the source and review the nights to import. Open Saved nights to review imported copies.</p><p>Import when I unlock is optional and checks a chosen source while Trifelle is active and unlocked. It does not sync while the app is closed. Source corrections and overlapping nights still need review.</p></section><section><h2>Delete local records</h2><p>Use Delete journal from this device and the confirmation shown in the app to remove the local journal. Exported files, backups and source wearable records are separate. For information about support correspondence, see <a href="privacy.html#deletion">retention and deletion</a>.</p></section><section><h2>Testing status</h2><p>Trifelle is in pre-release testing. A public Google Play or App Store launch has not been announced. Android preview builds allow screenshots for testing; store builds enable screenshot protection.</p><p>Trifelle is not a medical device. Predictions are experimental and are not medical advice or contraception guidance. Consult a healthcare professional for medical advice, diagnosis or treatment.</p></section>`,
);
const nativeText = `${policy.title}\n\nUpdated ${policy.updated} · ${policy.publisher}\n\n${policy.intro}\n\n${policy.sections.map((s) => `${s.title}\n\n${s.paragraphs.join('\n\n')}`).join('\n\n')}\n\n${policy.email}`;
const kotlin = `// Generated by scripts/build-privacy-pages.mjs from src/content/privacy.json.\npackage com.liambic.cyclehealth\n\ninternal object PrivacyPolicyText {\n  const val TEXT = ${JSON.stringify(nativeText).replaceAll('$', '\\$')}\n}\n`;
for (const [file, content] of [
  ['public/privacy.html', privacy],
  ['public/support.html', support],
  [
    'modules/cycle-health/android/src/main/java/com/liambic/cyclehealth/PrivacyPolicyText.kt',
    kotlin,
  ],
]) {
  // Prettier formats generated HTML; the content generator itself is deterministic.
  if (process.argv.includes('--check')) {
    const prettier = await import('prettier');
    const formatted = file.endsWith('.html')
      ? await prettier.format(content, { parser: 'html', ...(await prettier.resolveConfig(file)) })
      : content;
    const existing = (await readFile(file, 'utf8')).replaceAll('\r\n', '\n');
    if (existing !== formatted.replaceAll('\r\n', '\n'))
      throw new Error(`Generated privacy content is stale: ${file}`);
  } else {
    const prettier = await import('prettier');
    await writeFile(
      file,
      file.endsWith('.html')
        ? await prettier.format(content, {
            parser: 'html',
            ...(await prettier.resolveConfig(file)),
          })
        : content,
    );
  }
}
console.log('Privacy pages and native policy are current.');
